// Bulk import: Sotto blocks (from the Gemini skill, docs/gemini-skill.md) →
// SQL that posts them as "Sotto team (compiled from open sources)".
//
//   1. Save the skill's output, as many blocks as you like, in a text file,
//      e.g. inbox/blessing3.txt (anything around the blocks is ignored).
//   2. node scripts/blocks-to-sql.mjs inbox/*.txt  > supabase/import.sql
//   3. Read import.sql, then run it in the Supabase SQL editor.
//
// Blocks whose product doesn't match exactly one catalog model are listed on
// stderr and left out, so nothing lands on the wrong page.

import { readFile } from "node:fs/promises";
import { parseBlocks, reviewPost, problemPosts } from "../src/blocks.js";

const root = new URL("..", import.meta.url);
const catalog = JSON.parse(await readFile(new URL("data/catalog.json", root), "utf8"));
const norm = (s) => s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, " ").trim();
const names = catalog.items.map((i) => ({ id: i.id, n: norm(`${i.brand ?? ""} ${i.model}`), m: norm(i.model) }));

function match(product) {
  const p = norm(product);
  const exact = names.filter((x) => x.n === p || x.m === p);
  if (exact.length === 1) return exact[0].id;
  // Every word of the catalog name appears in the product name, longest name wins.
  const words = (s) => s.split(" ").filter(Boolean);
  const pw = new Set(words(p));
  const hits = names.filter((x) => words(x.n).every((w) => pw.has(w))).sort((a, b) => b.n.length - a.n.length);
  if (hits.length && (hits.length === 1 || hits[0].n.length > hits[1].n.length)) return hits[0].id;
  return null;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
const skipped = [];
for (const file of process.argv.slice(2)) {
  for (const b of parseBlocks(await readFile(file, "utf8"))) {
    const id = match(b.product);
    if (!id || !b.source) {
      skipped.push(`${file}: "${b.product}" ${!b.source ? "(no https source)" : "(no single catalog match)"}`);
      continue;
    }
    if (b.pros.length || b.cons.length) {
      const { title, body } = reviewPost(b);
      rows.push(`(${q(id)}, 'review', ${q(title)}, ${q(body)}, ${q(b.source)}, 'unknown', null::uuid)`);
    }
    for (const p of problemPosts(b)) rows.push(`(${q(id)}, 'issue', ${q(p.title)}, ${q(p.body)}, ${q(b.source)}, 'unknown', null::uuid)`);
  }
}
for (const s of skipped) console.error("skipped", s);
if (!rows.length) {
  console.error("nothing to import");
  process.exit(1);
}
console.log(`-- Generated by scripts/blocks-to-sql.mjs. Run supabase/reviews.sql first.
insert into public.reports (item_id, kind, title, body, evidence_url, purchase, author)
select * from (values
  ${rows.join(",\n  ")}
) as v(item_id, kind, title, body, evidence_url, purchase, author)
where not exists (select 1 from public.reports r where r.item_id = v.item_id and r.title = v.title and r.evidence_url = v.evidence_url);`);
console.error(`${rows.length} posts`);
