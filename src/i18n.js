export function makeT(lang) {
  const table = STRINGS[lang] ?? STRINGS.th;
  return (key, vars = {}) =>
    (table[key] ?? STRINGS.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}
